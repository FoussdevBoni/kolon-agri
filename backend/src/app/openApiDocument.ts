/** `mixed` : lecture publique, `?view=admin` réservé aux sessions administrateur. */
type Access = 'public' | 'session' | 'superAdmin' | 'mixed';

type PathParam = string | { name: string; schema: Record<string, unknown> };

interface OperationSpec {
  method: 'get' | 'post' | 'put' | 'patch' | 'delete';
  path: string;
  operationId: string;
  summary: string;
  tag: string;
  access: Access;
  body?: z.core.$ZodType;
  query?: z.ZodObject;
  pathParams?: PathParam[];
  /** Soumission publique : en-tête Idempotency-Key (UUID) obligatoire. */
  idempotent?: boolean;
  /** Corps binaire (types MIME acceptés) au lieu d'un corps JSON. */
  binaryBody?: string[];
  response: z.ZodType;
  successStatus?: number;
  paginated?: boolean;
  errors: number[];
}

function security(access: Access, method: OperationSpec['method']) {
  if (access === 'public') return [];
  if (access === 'mixed') return [{}, { sessionCookie: [] }];
  return method === 'get' ? [{ sessionCookie: [] }] : [{ sessionCookie: [], csrfToken: [] }];
}

function buildOperation(spec: OperationSpec) {
  const parameters = [
    ...(spec.pathParams ?? []).map((param) => ({
      name: typeof param === 'string' ? param : param.name,
      in: 'path',
      required: true,
      schema:
        typeof param === 'string' ? { type: 'string', pattern: '^[a-fA-F0-9]{24}$' } : param.schema,
    })),
    ...(spec.idempotent
      ? [
          {
            name: 'Idempotency-Key',
            in: 'header',
            required: true,
            description: 'UUID par soumission logique, réutilisé lors des nouvelles tentatives',
            schema: { type: 'string', format: 'uuid' },
          },
        ]
      : []),
    ...Object.entries(spec.query?.shape ?? {}).map(([name, field]) => ({
      name,
      in: 'query',
      required: !z.safeParse(field, undefined).success,
      schema: z.toJSONSchema(field, { ...schemaOptions, io: 'input' }),
    })),
  ];
  const successBody = createSuccessBodySchema(spec.response);
  return {
    tags: [spec.tag],
    operationId: spec.operationId,
    summary: spec.summary,
    security: security(spec.access, spec.method),
    ...(spec.access === 'superAdmin' ? { 'x-required-role': 'superAdmin' } : {}),
    ...(parameters.length > 0 ? { parameters } : {}),
    ...(spec.body
      ? { requestBody: { required: true, content: jsonContent(spec.body, 'input') } }
      : {}),
    ...(spec.binaryBody
      ? {
          requestBody: {
            required: true,
            content: Object.fromEntries(
              spec.binaryBody.map((type) => [
                type,
                { schema: { type: 'string', format: 'binary' } },
              ]),
            ),
          },
        }
      : {}),
    responses: {
      [String(spec.successStatus ?? 200)]: {
        description: spec.paginated ? 'Succès (meta : page, limit, total, totalPages)' : 'Succès',
        content: jsonContent(successBody),
      },
      ...Object.fromEntries(
        spec.errors.map((status) => [
          String(status),
          {
            description: errorDescriptions[status] ?? 'Erreur',
            content: jsonContent(apiErrorBodySchema),
          },
        ]),
      ),
    },
  };
}

