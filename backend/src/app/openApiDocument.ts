function buildPaths(): Record<string, Record<string, ReturnType<typeof buildOperation>>> {
  const paths: Record<string, Record<string, ReturnType<typeof buildOperation>>> = {};
  for (const spec of operations) {
    paths[spec.path] = { ...paths[spec.path], [spec.method]: buildOperation(spec) };
  }
  return paths;
}

