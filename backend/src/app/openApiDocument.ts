const schemaOptions = { unrepresentable: 'any' } as const;

function jsonContent(schema: z.core.$ZodType, io: 'input' | 'output' = 'output') {
  return { 'application/json': { schema: z.toJSONSchema(schema, { ...schemaOptions, io }) } };
}

